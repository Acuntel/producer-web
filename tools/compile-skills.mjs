// knowledge/skills/*.md -> lib/brain/skills-data.ts. Run after editing a skill.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../knowledge/skills/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
const entries = files.map((f) => ({ id: f.replace(/\.md$/, ""), text: readFileSync(new URL(f, dir), "utf8").trim() }));
const out = `// GENERATED by tools/compile-skills.mjs from knowledge/skills/*.md. Do not edit by hand.\nexport const SKILLS_DATA: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.id, e.text])), null, 0)};\n`;
writeFileSync(new URL("../lib/brain/skills-data.ts", import.meta.url), out);
console.log("compiled", entries.map((e) => `${e.id} (${e.text.length})`).join(", "));
