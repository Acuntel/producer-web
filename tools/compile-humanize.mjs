// Real drummers into groove templates. Reads data/dna/humanize.json (Groove MIDI: per style,
// per 16th slot, the median timing offset in ms and the median velocity of thousands of
// human hits) and writes lib/song/grooveHuman.ts. Timing is expressed relative to the
// downbeat (slot 0) in beats at 120 BPM, so amount 1 reproduces the measured pocket and
// the engine scales it with tempo. Accents are the velocity shape around the style mean.
// node tools/compile-humanize.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync("data/dna/humanize.json", "utf8"));
const MIN_HITS = 4000;
const BEAT_SEC = 0.5;   // 120 BPM reference
const out = {};
for (const [style, v] of Object.entries(src.styles)) {
  const slots = v.slots;
  const n = Object.values(slots).reduce((a, s) => a + (s.n ?? 0), 0);
  if (n < MIN_HITS) continue;
  const off = Array.from({ length: 16 }, (_, i) => slots[String(i)]?.offset_ms_median ?? 0);
  const vel = Array.from({ length: 16 }, (_, i) => slots[String(i)]?.velocity_median ?? null);
  const ref = off[0];
  const timing = off.map((ms) => Math.round(((ms - ref) / 1000 / BEAT_SEC) * 10000) / 10000);
  const present = vel.filter((x) => typeof x === "number");
  const mean = present.reduce((a, b) => a + b, 0) / Math.max(1, present.length);
  const accents = vel.map((x) => (typeof x === "number" ? Math.max(-0.6, Math.min(0.6, Math.round(((x - mean) / mean) * 100) / 100)) : 0));
  out[style] = { timing, accents, n };
}
const names = Object.keys(out).sort((a, b) => out[b].n - out[a].n);
const body = names.map((k) => `  "human-${k}": { timing: [${out[k].timing.join(", ")}], accents: [${out[k].accents.join(", ")}], n: ${out[k].n} },`).join("\n");
writeFileSync("lib/song/grooveHuman.ts", `// GENERATED by tools/compile-humanize.mjs from data/dna/humanize.json (Groove MIDI, real drummers).
// Timing = beats at 120 BPM relative to the downbeat at amount 1 (negative = early); accents = -1..1 around the style's mean velocity; n = hits measured.
export type HumanGroove = { timing: number[]; accents: number[]; n: number };
export const HUMAN_GROOVES: Record<string, HumanGroove> = {
${body}
};
export const HUMAN_GROOVE_NAMES = Object.keys(HUMAN_GROOVES);
`);
console.log(`wrote lib/song/grooveHuman.ts: ${names.length} styles (${names.join(", ")})`);
for (const k of names.slice(0, 4)) console.log(`  human-${k}: odd 16ths late by ${Math.round(out[k].timing.filter((_, i) => i % 2 === 1).reduce((a, b) => a + b, 0) / 8 * 500)} ms at 120, backbeat accent ${out[k].accents[4]}`);
